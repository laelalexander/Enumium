"""Write tags.csv (Studio 5000 import style) and io_map.st from design/io.json.

The I/O list is the single source: re-run this after io_list.py changes.
Usage: python3 gen_tags.py
"""
import csv, json, pathlib

HERE = pathlib.Path(__file__).parent
IO = json.loads((HERE.parents[1] / "design" / "io.json").read_text())

TYPE = {"DI": "BOOL", "DO": "BOOL", "AI": "REAL"}


def main():
    rows = IO["io"]
    with open(HERE / "tags.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["TYPE", "SCOPE", "NAME", "DESCRIPTION", "DATATYPE", "SPECIFIER", "ATTRIBUTES"])
        for r in rows:
            scope = "PLC601" if r["plc"] == "601" else "PLC602"
            w.writerow(["ALIAS", scope, r["tag"], f'{r["device"]} {r["desc"]} | wire {r["wire"]} | cable {r["cable"]}',
                        "", r["address"], "(RADIX := Decimal, ExternalAccess := Read/Write)"])
    # IEC 61131-3 copy-in / copy-out map for runtimes without alias tags (CODESYS, OpenPLC)
    out = ["(* Generated by gen_tags.py from design/io.json. Do not edit by hand. *)"]
    for plc in ("601", "602"):
        sel = [r for r in rows if r["plc"] == plc]
        out.append(f"\nVAR_GLOBAL (* PLC-{plc} physical I/O *)")
        for r in sel:
            at = {"DI": "%IX", "DO": "%QX", "AI": "%IW"}[r["type"]] + f'{r["slot"]}.{r["channel"]}'
            out.append(f'    {r["tag"]:<22} AT {at:<8} : {TYPE[r["type"]]};  (* {r["device"]}: {r["desc"]}; wire {r["wire"]} *)')
        out.append("END_VAR")
    (HERE / "io_map.st").write_text("\n".join(out) + "\n")
    print(len(rows), "tags written")


if __name__ == "__main__":
    main()
