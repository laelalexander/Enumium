"""Collect every part that still carries [verify] (supplier PN, MPN, land pattern) across the rev B boards and the harness,
and write electrical/part-verification.md.  Run after any design change."""
import os
import sys

KG = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, KG)
import build   # noqa: E402

BOARDS = [('cbp8', 'CBP-8 GPU backplane (x8 per tower)'), ('cpd1', 'CPD-1 column power (x4)'),
          ('ccm1', 'CCM-1 cooling controller (x4)'), ('tcd1', 'TCD-1 Peltier driver (x4)')]
LANDS = {
    'ts2b:TE_2364427_PCIe_x16_Vertical_SMT': 'TE 2364427 customer drawing: pad 0.6 x 2.0, row pitch 7.70, pin 11/12 key gap 3.30, '
                                             'peg holes.  Highest risk part: 164 SMT pins carrying 8 Gen4 lanes.',
    'ts2b:Amphenol_G97R22332HR_MCIO_8i_RA_SMT': 'Amphenol G97R22332HR drawing: 0.60 mm pitch, A/B row offsets, shield tabs, '
                                                'hold-down pegs.',
    'ts2b:Amphenol_10160920-1240100LF_12V-2x6_RA': 'Amphenol 10160920-1240100LF drawing: 3.0 mm pitch power rows, 4 sense pins, '
                                                   'board locks.',
    'ts2b:Amphenol_CRPS_PwrBlade_Vertical_PressFit': 'Amphenol / FCI PwrBlade CRPS receptacle: confirm VERTICAL variant that mates '
                                                     'the Murata D1U54T card edge with the board perpendicular to the PSU; '
                                                     'press-fit hole sizes; blade-to-signal pin assignment vs Murata pin table.',
    'ts2b:Power_Stud_M6_PressFit': 'PEM FHS-M6 (or Wurth REDCUBE) hole size for the chosen board thickness.',
    'ts2b:Power_Stud_M5_PressFit': 'PEM FHS-M5 hole size for 1.6 mm board.',
}


def main():
    out = ['# TS-2 rev B: part verification list', '',
           'Generated by `electrical/kgen/verify_list.py` from the board design tables. Every line is something a person must',
           'check against the vendor drawing or a live distributor page before the boards are ordered. The boards pass DRC',
           'and a schematic-to-design netlist check; these items are the remaining risk.', '',
           '## 1. Custom land patterns (highest priority)', '',
           '| Footprint | Used on | What to check |', '|---|---|---|']
    used = {}
    parts = {}
    for b, title in BOARDS:
        D = build.load(b).D
        for p in D.parts:
            if p['fp'] in LANDS:
                used.setdefault(p['fp'], set()).add(b.upper())
            txt = ' '.join(str(p.get(k, '')) for k in ('mpn', 'spn', 'desc'))
            if 'verify' in txt.lower():
                key = (p['mpn'].replace(' [verify]', ''), p['mfr'])
                e = parts.setdefault(key, dict(desc=p['desc'], fp=p['fp'].split(':')[-1], boards={}, spn=p['spn']))
                e['boards'][b.upper()] = e['boards'].get(b.upper(), 0) + 1
    for fp, why in LANDS.items():
        out.append('| `%s` | %s | %s |' % (fp.split(':')[1], ', '.join(sorted(used.get(fp, []))) or '-', why))
    out += ['', '## 2. Parts with an unverified MPN or supplier number', '',
            '| MPN | Manufacturer | Description | Footprint | Qty per board | Supplier PN (to confirm) |',
            '|---|---|---|---|---|---|']
    for (mpn, mfr), e in sorted(parts.items()):
        q = ', '.join('%s x%d' % (b, n) for b, n in sorted(e['boards'].items()))
        out.append('| %s | %s | %s | %s | %s | %s |' % (mpn, mfr, e['desc'].replace('|', '/'), e['fp'], q,
                                                        e['spn'].replace(' [verify]', '').replace('[verify]', '') or '-'))
    out += ['', '## 3. Design values to confirm on the first article', '',
            '- MIC2587-1 TIMER capacitor (22 nF on CBP-8): fault delay with a 25 A GPU inrush; scope the gate on the first card.',
            '- CBP-8 hot-swap breaker 33 A (1.5 mOhm): confirm against the RTX PRO 6000 Max-Q peak (12V-2x6 600 W class cable).',
            '- CRPS PMBus default address and ADDR pin behaviour (CPD-1 R107/207/307/407 fitted DNP).',
            '- CRPS VSB voltage (12 V assumed) and remote sense polarity (V1_SENSE+ / V1_SENSE_R).',
            '- Omron G5V-1 contact pin numbering in the KiCad symbol (NO vs NC on CCM-1 J22 pins 2/3).',
            '- SDP810 connector type (JST GH 4P assumed) and SHT45 probe pinout (CCM-1 J7/J8).',
            '- TEC module operating point: 14 A per channel continuous; IHLP-5050 6.8 uH saturation at 17 A peak.',
            '- MCIO cable insertion loss for the 1.25 m and 1.5 m assemblies (upper group): see the Gen4 loss budget in',
            '  `electrical/ARCHITECTURE.md`; fall back to a redriver card in the host if a link trains below 16 GT/s.',
            '', '## 4. Harness', '',
            '- Molex 43030-0038 as the 18 AWG Micro-Fit crimp; 43030-0007 for 20-24 AWG.',
            '- 4/0 AWG two-hole M8 compression lugs and the strap hole pattern on TS2B-232 / TS2B-233.',
            '- M12 8-pin A-coded panel receptacle for the chiller bulkhead; chiller remote set-point input range (0-10 V).',
            '- MCIO and 12V-2x6 cable assembly part numbers at the listed lengths (TS2B-ELE-102 sheet "Cables").']
    path = os.path.join(KG, '..', 'part-verification.md')
    open(path, 'w').write('\n'.join(out) + '\n')
    print('wrote', os.path.normpath(path), len(parts), 'parts to verify')


if __name__ == '__main__':
    main()
