"""RushPCB-ready turnkey package for one board.

fab/<project>-rushpcb.zip contains:
  gerbers/        RS-274X (Protel extensions) for every copper / mask / paste / silk layer + Edge.Cuts
  drill/          Excellon PTH and NPTH (mm), drill map PDF
  <p>-bom.xlsx    BOM (grouped: item, qty, refs, value, description, manufacturer, MPN, supplier PN, footprint,
                  side, DNP), a DNP list, the fab notes and the test notes as sheets
  <p>-centroid-mm.csv / -centroid-in.csv   pick-and-place (ref, value, footprint, x, y, rotation, side)
  <p>-assembly-top.pdf / -assembly-bottom.pdf   Fab + silk + outline (pin-1 / polarity marks from the footprints)
  <p>-schematic.pdf, <p>-fab-notes.txt, <p>-test-notes.txt, <p>-drc.rpt, hs-pairs.csv (if any)
"""
import csv
import io
import os
import shutil
import subprocess
import zipfile

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter


def run(args):
    r = subprocess.run(args, capture_output=True, text=True)
    if r.returncode:
        print('  !', ' '.join(args[:4]), r.stderr.strip()[:200])
    return r.returncode == 0


def cu_layers(n):
    return ['F.Cu'] + ['In%d.Cu' % i for i in range(1, n - 1)] + ['B.Cu']


def bom_rows(D):
    groups = {}
    for p in D.parts:
        if not p.get('bom', True):
            continue
        key = (p['value'], p['fp'], p['mpn'], p['mfr'], bool(p.get('dnp')))
        groups.setdefault(key, []).append(p)

    def refkey(r):
        import re
        m = re.match(r'([A-Z]+)(\d+)', r)
        return (m.group(1), int(m.group(2))) if m else (r, 0)
    rows = []
    for (val, fp, mpn, mfr, dnp), ps in sorted(groups.items(), key=lambda kv: refkey(sorted(p['ref'] for p in kv[1])[0])):
        refs = sorted((p['ref'] for p in ps), key=refkey)
        sides = ''.join(sorted({p.get('side', 'F') for p in ps}))
        rows.append(dict(qty=len(ps), refs=' '.join(refs), value=val, desc=ps[0]['desc'], mfr=mfr, mpn=mpn,
                         spn=ps[0].get('spn', '') or (('LCSC ' + ps[0]['lcsc']) if ps[0].get('lcsc') else ''), fp=fp.split(':')[-1], side={'F': 'Top', 'B': 'Bottom', 'BF': 'Both'}[sides],
                         dnp='DNP' if dnp else '', unit=ps[0].get('price', 0.0)))
    return rows


def fab_notes(D):
    f = D.fab
    lines = ['%s  %s  rev %s - FABRICATION NOTES' % (D.project.upper(), D.title, D.rev), '=' * 78,
             '1. Board size: %s. Outline per Edge.Cuts gerber; corner radius %.1f mm. Tolerance +/-0.15 mm.' % (
                 f.get('size', '%.1f x %.1f mm' % (D.W, D.H)), D.corner_r),
             '2. Layers: %d. Finished thickness: %s.' % (D.layers, f.get('thickness', '%.1f mm' % D.thickness)),
             '3. Material: %s.' % f.get('material', 'FR-4 Tg 170, IPC-4101/126'),
             '4. Copper: %s.' % f.get('copper', '1 oz all layers'),
             '5. Surface finish: %s. Solder mask: %s. Silkscreen: %s.' % (f.get('finish', 'ENIG'), f.get('mask', 'green LPI'),
                                                                          f.get('silk', 'white')),
             '6. Minimum track / space: %s. Minimum drill: %s.' % (f.get('min_track', '0.15 / 0.15 mm'), f.get('min_drill', '0.30 mm')),
             '7. Vias: %s.' % f.get('vias', 'through, tented both sides'),
             '8. Controlled impedance: %s.' % f.get('impedance', 'none'),
             '9. Stack-up (top to bottom) is in the board file and the table below; the fab may adjust dielectric',
             '   thickness and trace width to hit the impedance, keeping the layer order and copper weights.',
             '10. Quality: %s. Electrical test: %s.' % (f.get('ipc', 'IPC-6012 class 2'), f.get('test', '100 % netlist')),
             '11. Board marking: fab date code and UL mark on the bottom silk near the lower-left corner.',
             '12. Assembly: RoHS lead-free, IPC-A-610 class 2. Both sides populated where the BOM says Bottom.',
             '13. Parts marked [verify] in the BOM: confirm land pattern / supplier number before kitting (see the',
             '    part-verification list in the project docs). Do not substitute connectors without approval.',
             '14. This design was generated by script and has passed DRC and a schematic-netlist check; it still needs',
             '    a human engineering review before release to production.',
             '15. Centroid files: origin = lower-left corner of the board outline seen from the top; X right, Y up;',
             '    bottom-side parts are given in top view (KiCad convention). mm and inch files carry the same data.']
    if D.fab.get('press_fit'):
        lines.append('16. Press-fit: %s.' % D.fab['press_fit'])
    if D.stackup:
        lines.append('')
        lines.append('STACK-UP')
        for l in D.stackup.splitlines():
            l = l.strip()
            if l.startswith('(layer "') and ('copper' in l or 'dielectric' in l):
                lines.append('  ' + l.replace('(layer ', '').replace(')', '').replace('(', ''))
    return '\n'.join(lines) + '\n'


def make(D, out, m=None):
    fab = os.path.join(out, 'fab')
    pkg = os.path.join(fab, 'rushpcb')
    shutil.rmtree(pkg, ignore_errors=True)
    os.makedirs(os.path.join(pkg, 'gerbers'))
    os.makedirs(os.path.join(pkg, 'drill'))
    pcb = os.path.join(out, D.project + '.kicad_pcb')
    schf = os.path.join(out, D.project + '.kicad_sch')
    P = D.project
    layers = cu_layers(D.layers) + ['F.Paste', 'B.Paste', 'F.SilkS', 'B.SilkS', 'F.Mask', 'B.Mask', 'Edge.Cuts']
    run(['kicad-cli', 'pcb', 'export', 'gerbers', '-o', os.path.join(pkg, 'gerbers') + '/', '-l', ','.join(layers),
         '--subtract-soldermask', pcb])
    run(['kicad-cli', 'pcb', 'export', 'drill', '-o', os.path.join(pkg, 'drill') + '/', '--format', 'excellon',
         '--excellon-units', 'mm', '--excellon-separate-th', '--generate-map', '--map-format', 'pdf', pcb])
    # centroid
    tmp = os.path.join(fab, P + '-pos-raw.csv')
    run(['kicad-cli', 'pcb', 'export', 'pos', '-o', tmp, '--format', 'csv', '--units', 'mm', '--side', 'both', pcb])
    rows = list(csv.DictReader(open(tmp)))
    dnp = {p['ref'] for p in D.parts if p.get('dnp')}
    nopos = {p['ref'] for p in D.parts if not p.get('pos', True)}
    for unit, k in (('mm', 1.0), ('in', 1 / 25.4)):
        with open(os.path.join(pkg, '%s-centroid-%s.csv' % (P, unit)), 'w', newline='') as f:
            w = csv.writer(f)
            w.writerow(['Designator', 'Value', 'Footprint', 'Mid X (%s)' % unit, 'Mid Y (%s)' % unit, 'Rotation', 'Layer', 'Fit'])
            for r in rows:
                ref = r['Ref']
                if ref in nopos:
                    continue
                # board origin = lower-left corner of the outline, seen from the top (bottom parts: top view)
                x = (float(r['PosX']) - D.X0) * k
                y = (float(r['PosY']) + D.Y0 + D.H) * k
                w.writerow([ref, r['Val'], r['Package'], '%.4f' % x, '%.4f' % y, r['Rot'],
                            'Top' if r['Side'] == 'top' else 'Bottom', 'DNP' if ref in dnp else 'Fit'])
    os.remove(tmp)
    # assembly drawings (fab layer carries outlines, ref des and pin-1 / polarity marks)
    run(['kicad-cli', 'pcb', 'export', 'pdf', '-o', os.path.join(pkg, P + '-assembly-top.pdf'), '-l',
         'F.Fab,F.SilkS,Edge.Cuts', '--ibt', pcb])
    run(['kicad-cli', 'pcb', 'export', 'pdf', '-o', os.path.join(pkg, P + '-assembly-bottom.pdf'), '-l',
         'B.Fab,B.SilkS,Edge.Cuts', '--ibt', '-m', pcb])
    run(['kicad-cli', 'sch', 'export', 'pdf', '-o', os.path.join(pkg, P + '-schematic.pdf'), schf])
    for lay, nm in (('F.Cu,F.SilkS,Edge.Cuts', 'top-copper'), ('B.Cu,B.SilkS,Edge.Cuts', 'bottom-copper')):
        run(['kicad-cli', 'pcb', 'export', 'pdf', '-o', os.path.join(fab, '%s-%s.pdf' % (P, nm)), '-l', lay] +
            (['-m'] if nm.startswith('bottom') else []) + [pcb])
    # notes
    notes = fab_notes(D)
    open(os.path.join(pkg, P + '-fab-notes.txt'), 'w').write(notes)
    tests = '%s rev %s - TEST NOTES\n%s\n' % (D.project.upper(), D.rev, '=' * 60) + \
        '\n'.join('%d. %s' % (i + 1, t) for i, t in enumerate(D.test_notes)) + '\n'
    open(os.path.join(pkg, P + '-test-notes.txt'), 'w').write(tests)
    drc = os.path.join(fab, P + '-drc.rpt')
    if os.path.exists(drc):
        shutil.copy(drc, pkg)
    hs = os.path.join(out, 'build', 'hs-pairs.json')
    if os.path.exists(hs):
        import json
        rep = json.load(open(hs))
        with open(os.path.join(pkg, P + '-hs-pairs.csv'), 'w', newline='') as f:
            w = csv.DictWriter(f, fieldnames=list(rep[0].keys()))
            w.writeheader()
            w.writerows(rep)
    # BOM workbook
    wb = Workbook()
    ws = wb.active
    ws.title = 'BOM'
    hdr = ['Item', 'Qty', 'Designators', 'Value', 'Description', 'Manufacturer', 'MPN', 'Supplier PN', 'Footprint', 'Side',
           'DNP', 'Unit price USD (est.)', 'Ext. USD (est.)']
    ws.append(['%s  %s  rev %s - Bill of Materials (qty per board)' % (P.upper(), D.title, D.rev)])
    ws.append([])
    ws.append(hdr)
    for c in range(1, len(hdr) + 1):
        ws.cell(row=3, column=c).font = Font(bold=True, color='FFFFFF')
        ws.cell(row=3, column=c).fill = PatternFill('solid', fgColor='1F3A5F')
    ws['A1'].font = Font(bold=True, size=13)
    tot = 0.0
    br = bom_rows(D)
    for i, r in enumerate(br):
        ext = 0.0 if r['dnp'] else r['qty'] * r['unit']
        tot += ext
        ws.append([i + 1, r['qty'], r['refs'], r['value'], r['desc'], r['mfr'], r['mpn'], r['spn'], r['fp'], r['side'],
                   r['dnp'], round(r['unit'], 3), round(ext, 2)])
    ws.append([])
    ws.append(['', '', '', '', 'Estimated parts cost per board (excl. DNP, before price breaks)', '', '', '', '', '', '', '',
               round(tot, 2)])
    widths = [6, 5, 40, 16, 60, 24, 24, 26, 34, 8, 6, 12, 12]
    for i, wd in enumerate(widths):
        ws.column_dimensions[get_column_letter(i + 1)].width = wd
    for row in ws.iter_rows(min_row=4):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical='top')
    ws.freeze_panes = 'A4'
    d2 = wb.create_sheet('DNP')
    d2.append(['Designator', 'Value', 'Description'])
    for p in D.parts:
        if p.get('dnp'):
            d2.append([p['ref'], p['value'], p['desc']])
    for title, text in (('Fab notes', notes), ('Test notes', tests)):
        s = wb.create_sheet(title)
        s.column_dimensions['A'].width = 120
        for line in text.splitlines():
            s.append([line])
    wb.save(os.path.join(pkg, P + '-bom.xlsx'))
    shutil.copy(os.path.join(pkg, P + '-bom.xlsx'), os.path.join(fab, P + '-bom.xlsx'))
    # zip
    z = os.path.join(fab, P + '-rushpcb.zip')
    with zipfile.ZipFile(z, 'w', zipfile.ZIP_DEFLATED) as zf:
        for root, _, files in os.walk(pkg):
            for fn in sorted(files):
                full = os.path.join(root, fn)
                zf.write(full, os.path.relpath(full, pkg))
    # previews
    for nm in ('top-copper', 'bottom-copper'):
        pdf = os.path.join(fab, '%s-%s.pdf' % (P, nm))
        if os.path.exists(pdf):
            run(['pdftoppm', '-r', '60', '-png', '-singlefile', pdf, os.path.join(fab, '%s-%s' % (P, nm))])
    n = sum(len(f) for _, _, f in os.walk(pkg))
    print('fab package: %s (%d files), BOM lines %d, est. parts USD %.0f' % (z, n, len(br), tot))
    return z
