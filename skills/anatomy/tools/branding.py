"""Customer-facing branding for every Anatomy drawing, sheet, cover page and PDF.

All Anatomy project drawings are issued by Noitavonne Manufacturing, NERO Design Studios CAD
(Prototype / Mechanical / CAD / Industrial Design), on the Noitavonne on-prem engineering system.
Nero and Anatomy are both systems built by Noitavonne.

Rules (see references/drawings.md, "Branding"):
  * Title block DRAWN / PREPARED BY = DRAWN_BY. Never a script name, tool or library (no build123d,
    CadQuery, FreeCAD, svgwrite, PyMuPDF), never "Claude", never an internal path.
  * Every sheet carries FOOTER in the bottom margin (svg_footer / pdf_footer below).
  * Cover pages use COVER_NOTE in place of any "generated from ... by ...py" line.
  * PDFs get PDF_METADATA.
Import this module (copy it next to a project's generator if the skill folder is not on sys.path).
"""

COMPANY = "Noitavonne Manufacturing"
STUDIO = "NERO Design Studios"
DISCIPLINES = "Prototype / Mechanical / CAD / Industrial Design"
DRAWN_BY = "NERO Design Studios"
FOOTER = (f"{COMPANY}  |  {STUDIO} CAD ({DISCIPLINES})  |  "
          "Noitavonne on-prem engineering system. Nero and Anatomy are built by Noitavonne.")
COVER_NOTE = (f"Prepared by {COMPANY}, {STUDIO} CAD ({DISCIPLINES}), "
              "on the Noitavonne on-prem engineering system.")
PDF_METADATA = {"author": f"{COMPANY} - {STUDIO}", "creator": f"{STUDIO} CAD",
                "producer": f"{COMPANY} on-prem engineering system (Nero / Anatomy)"}

# Words that must never appear in customer-facing drawing text (checked by check_branding).
FORBIDDEN = ("build123d", "cadquery", "freecad", "techdraw", "svgwrite", "pymupdf", "matplotlib", "ezdxf",
             "claude", "generated by", "generated from", "make_drawings", ".py")


def svg_footer(width, height, size=2.0, y=None, x=None, anchor="middle"):
    """SVG <text> footer in user units (mm for A3 mm sheets, px for ARCH D px sheets).
    Default: centred in the bottom margin, baseline 0.6 % of the sheet height above the edge."""
    from xml.sax.saxutils import escape
    x = width / 2 if x is None else x
    y = height - max(size * 0.9, height * 0.006) if y is None else y
    return (f'<text font-family="Arial,Helvetica,sans-serif" font-size="{size}" fill="#333" x="{x:.1f}" '
            f'y="{y:.1f}" text-anchor="{anchor}">{escape(FOOTER)}</text>')


def add_svgwrite_footer(d, width_mm, height_mm, size=2.0):
    """Same footer for an svgwrite.Drawing in mm user units."""
    d.add(d.text(FOOTER, insert=(width_mm / 2, height_mm - 1.8), font_size=size, fill="#333",
                 text_anchor="middle", font_family="Arial"))


def mpl_footer(fig, size=6):
    """Same footer for a matplotlib figure."""
    fig.text(0.5, 0.006, FOOTER, ha="center", va="bottom", fontsize=size, color="#333")


def pdf_metadata(doc, title=""):
    """Set branded metadata on a PyMuPDF document."""
    md = dict(doc.metadata or {})
    md.update(PDF_METADATA)
    if title:
        md["title"] = title
    doc.set_metadata(md)


def drawn_by(value=None):
    """Title-block DRAWN value: a person's name or initials pass through; any tool, script, 'Anatomy' or 'Claude' credit
    becomes DRAWN_BY."""
    v = (value or "").strip()
    if not v or check_branding(v) or "anatomy" in v.lower() or "/" in v:
        return DRAWN_BY
    return v


def check_branding(text):
    """Return the forbidden credits found in a sheet's text (empty list = clean)."""
    low = text.lower()
    return [w for w in FORBIDDEN if w in low]
