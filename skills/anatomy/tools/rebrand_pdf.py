"""Check or fix the branding of an existing drawing PDF (any generator).

    python rebrand_pdf.py --check set.pdf [more.pdf ...]     report forbidden credits, exit 1 if any
    python rebrand_pdf.py set.pdf [--no-backup]               fix in place (keeps set.pre-branding.pdf)

Fixing: title-block credits ("Anatomy (from CAD)", "plant/mechsheet.py", "Anatomy / Claude ...") become
"NERO Design Studios"; "Generated from/by ..." lines become the Noitavonne cover note; every page gets the
Noitavonne / NERO Design Studios footer in a free strip of its margin; PDF metadata is branded. Text that
mentions a tool or path in any other way is reported, not rewritten, so a person can word it properly.
Needs PyMuPDF.
"""
import argparse
import re
import shutil
import sys
from pathlib import Path

import fitz

sys.path.insert(0, str(Path(__file__).resolve().parent))
import branding as B  # noqa: E402

TOOLS = re.compile(r"\b(build123d|cadquery|ocp|occ|hlr|matplotlib|ezdxf|svgwrite|pymupdf|numpy|zrender|techdraw|freecad)\b", re.I)
PY = re.compile(r"[\w\-./\\:]*[\w\-]+\.py\b(\s*\([^)]*\))?", re.I)
PAREN = re.compile(r"\s*\((?:[^()]*?)\)")
GENERATED = re.compile(r"\bgenerated (from|by)\b", re.I)
# Internal file references -> plain document names (customer-facing wording).
PATHS = [
    (r"\(=\s*(prototype/)?bom/bom\.csv\)", "(= BOM)"),
    (r"\((item = BOM line, )?(prototype/)?bom/bom\.csv\)", lambda m: "(item = BOM line)" if m.group(1) else "(BOM)"),
    (r"(prototype/)?bom/bom\.csv", "the BOM"),
    (r"(from|keys to) the BOM lines", r"\1 BOM lines"),
    (r"\b(also|CSV:)\s*[\w\-/]*WIRELIST[\w\-]*\.csv", lambda m: "also supplied as CSV" if m.group(1).lower() == "also" else "CSV supplied"),
    (r"[\w\-/]*WIRELIST[\w\-]*\.csv", "the wire list CSV"),
    (r"[\w\-/]*TUBELIST[\w\-]*\.csv", "the tube list CSV"),
    (r"(see |per )?(prototype/)?print/print-plan\.md", lambda m: (m.group(1) or "") + "the print plan"),
    (r"(prototype/)?print/gcode/", "the G-code package"),
    (r"assembly/steps\.json steps", "assembly steps"),
    (r"\(assembly/steps\.json\)", "(assembly steps)"),
    (r"assembly/steps\.json", "the assembly steps"),
    (r"\s*\((mechanical/)?assembled/assembly\.json\)", ""),
    (r"(mechanical/)?assembled/assembly\.json", "the assembled model"),
    (r"(mechanical/)?stackups/[\w\-]+\.md", "analysis on file"),
    (r"(thermal-fluid/)?thermal\.md", "thermal analysis on file"),
    (r"calc/[\w\-]+\.md", "calculations on file"),
    (r"build/3-fabricate/pcb/([\w\-]+)\.zip", r"the \1 package"),
    (r"README\.md lists every sheet\.?", "The sheet index lists every sheet."),
    (r"\b(?:mechanical/)?step/([\w\-.]+\.step)\b", r"\1"),
    (r"\bSTEP (in )?mechanical/step/", "STEP files"),
    (r"\bmechanical/step\b", "the STEP files"),
    (r"\bSource: [\w\-/]*\.py \(([\w\-]+)\)", r"Source: CAD model (\1)"),
    (r"^(\d+\.\s*)?Regenerate:.*$", r"\1Drawings are updated from the CAD model at every revision."),
    (r"\b(also|ALSO) (?:[\w\-]+/)+([\w\-]+\.csv)", r"\1 \2"),
    (r"\b(?:[\w\-]+/)+([\w\-]+\.(csv|json|step|stl|zip|dxf|svg|pdf))\b", r"\1"),
    (r"(?<![\w/])(?:[\w\-]+/)+(?=[\s,;.)]|$)", "on file"),
    (r"\belectrical/ \(KiCad\)", "the KiCad design"),
]
PY_NAMES = [(r"[\w\-/]*mechanism_check\.py", "the mechanism check"), (r"[\w\-/]*\bpanel\.py", "the panel layout check"),
            (r"[\w\-/]*\bparams\.py", "the design parameters"), (r"[\w\-/]*design\.py", "the board design"),
            (r"[\w\-/]*wiring\.py", "the wiring model"), (r"\bbom\.csv", "the BOM")]


FILLER = set("b rep hidden line lines views view section sections render rendered of the cad meshes mesh solids solid "
              "assembled poly hlr from table outlines d cut z buffer planar kg g sheet by flat parts and with standard "
              "drawn source".split())


def _clean(t):
    """Customer-facing rewrite of one text span, or the same text when nothing needs changing."""
    s = t
    if re.fullmatch(r"\s*generated by\s*:?\s*", s, re.I):
        return "DRAWN BY"
    if len(s) <= 60 and re.match(r"\s*(anatomy|claude)\b", s, re.I) and not re.search(r"\bproject\b", s, re.I):
        return B.DRAWN_BY
    if re.fullmatch(r"\s*[\w\-]+\.py\s*", s):
        return B.DRAWN_BY
    if len(PY.findall(s)) > 1 and not re.sub(r"[\s,;.]", "", PY.sub("", s)):
        return ""
    s = re.sub(r"\bgenerated from the (build123d|cadquery) (solids?|model)( \([^)]*\))?", r"drawn from the CAD \2", s, flags=re.I)
    if GENERATED.search(s):  # a whole "generated from/by ..." sentence becomes the branded cover note
        parts = re.split(r"(?<=[.;])\s+(?=[A-Z0-9])", s)
        s = " ".join(B.COVER_NOTE if GENERATED.search(x) else x for x in parts)
    s = re.sub(r"^\s*(matplotlib|build123d|cadquery)\s+from\b", "Drawn from", s, flags=re.I)
    s = re.sub(r"\bdrawn by script from the build123d solids", "Drawn from the CAD solids", s, flags=re.I)
    s = re.sub(r"\bby script\b\s*", "", s, flags=re.I)
    for a, b in PATHS:
        s = re.sub(a, b, s, flags=re.I)
    # parentheticals that only name a tool, script or path
    s = PAREN.sub(lambda m: "" if (TOOLS.search(m.group(0)) or PY.search(m.group(0)) or "/" in m.group(0) and ".py" in m.group(0).lower()) else m.group(0), s)
    s = re.sub(r"\b(the )?[\w\-]+\.py (solids?|hole positions|solid)\b", r"the CAD \2", s, flags=re.I)
    s = re.sub(r"\((NB1_MODEL|SC1)\.PY( = STEP)?\)", "", s)
    for a, b in PY_NAMES:
        s = re.sub(a, b, s, flags=re.I)
    s = re.sub(r"\s+(with|using|via)\s+[^.;]*?\b(build123d|cadquery|matplotlib|ezdxf|svgwrite|pymupdf|numpy|ocp)\b[^.;]*", "", s, flags=re.I)
    if TOOLS.search(s) or PY.search(s):
        lead = re.match(r"^\s*(\d[\d.,]*\s*(kg|g)\b|SHEET BY:)", s, re.I)
        rest = [w for w in re.findall(r"[A-Za-z]+", TOOLS.sub(" ", PY.sub(" ", s))) if w.lower() not in FILLER]
        if len(rest) <= 2:
            s = (lead.group(1) + (" " if lead.group(1).endswith(":") else "  ") if lead else "") + B.DRAWN_BY
        else:
            s = PY.sub("the CAD model", s)
            s = re.sub(r"\bthe build123d (solids?|CAD)\b", r"the CAD \1", s, flags=re.I)
            s = TOOLS.sub("CAD", s)
    s = re.sub(r"\s{3,}", "  ", s).replace(" .", ".").replace(" ,", ",").replace("()", "").replace("..", ".")
    s = re.sub(r"^\s*,\s*", "", s)
    return s


def _spans(page):
    """Text lines (spans on one baseline joined), so a sentence split across fonts is rewritten as a whole."""
    for b in page.get_text("dict")["blocks"]:
        for ln in b.get("lines", []):
            sp = [s for s in ln["spans"] if s["text"]]
            if not sp or not "".join(s["text"] for s in sp).strip():
                continue
            if ln.get("dir", (1, 0)) != (1, 0):  # rotated text: keep per span
                yield from (s for s in sp if s["text"].strip())
                continue
            first = max(sp, key=lambda s: len(s["text"].strip()))
            yield {"text": "".join(s["text"] for s in sp), "origin": sp[0]["origin"], "size": first["size"],
                   "color": first["color"], "bbox": (min(s["bbox"][0] for s in sp), min(s["bbox"][1] for s in sp),
                                                     max(s["bbox"][2] for s in sp), max(s["bbox"][3] for s in sp))}


INTERNAL_PATH = re.compile(r"\b[\w\-]+/[\w\-./]+\.(py|csv|md|step|stl|json|zip|kicad_pcb)\b", re.I)


def classify(text):
    t = text.strip()
    if B.FOOTER in t or t == B.COVER_NOTE:
        return None
    if B.check_branding(t.replace(B.COVER_NOTE, "")) or INTERNAL_PATH.search(t) or TOOLS.search(t) or PY.search(t):
        return "fix" if _clean(t) != t else "warn"
    return None


def _fit(text, size, width):
    while size > 3 and fitz.get_text_length(text, "helv", size) > width:
        size *= 0.92
    return size


def place_footer(page):
    r = page.rect
    blocks = [fitz.Rect(b[:4]) for b in page.get_text("blocks")]
    fs0 = max(4.5, r.width * 0.0048)
    for scale in (1.0, 0.85, 0.7):
        fs = fs0 * scale
        L = fitz.get_text_length(B.FOOTER, "helv", fs)
        for y in (r.height - max(fs * 0.6, r.height * 0.004), fs * 1.2):
            for x in ((r.width - L) / 2, r.width * 0.03, r.width * 0.97 - L):
                box = fitz.Rect(x - 2, y - fs, x + L + 2, y + fs * 0.3)
                if box.x0 >= 0 and box.x1 <= r.width and not any(box.intersects(b) for b in blocks):
                    return x, y, fs
    fs = fs0 * 0.7
    return (r.width - fitz.get_text_length(B.FOOTER, "helv", fs)) / 2, r.height - fs * 0.6, fs


def process(path, fix, backup=True):
    doc = fitz.open(path)
    report = []
    for pno, page in enumerate(doc):
        todo = []
        for s in _spans(page):
            kind = classify(s["text"])
            if kind:
                report.append((pno + 1, kind, s["text"].strip()))
                if kind == "fix":
                    todo.append((kind, s))
        if not fix:
            continue
        for kind, s in todo:
            ox, oy = s["origin"]  # tight box around the glyphs so labels just above/below survive
            page.add_redact_annot(fitz.Rect(s["bbox"][0], oy - s["size"] * 0.72, s["bbox"][2], oy + s["size"] * 0.18), fill=(1, 1, 1))
        if todo:
            page.apply_redactions(images=fitz.PDF_REDACT_IMAGE_NONE, graphics=fitz.PDF_REDACT_LINE_ART_NONE)
        for kind, s in todo:
            new = _clean(s["text"].strip())
            width = s["bbox"][2] - s["bbox"][0]
            if B.COVER_NOTE in new:  # cover lines may use the rest of the page width
                width = max(width, page.rect.width - s["origin"][0] - page.rect.width * 0.03)
            if not new.strip():
                continue
            page.insert_text(s["origin"], new, fontsize=_fit(new, s["size"], width), fontname="helv",
                             color=tuple(((s["color"] >> k) & 255) / 255 for k in (16, 8, 0)))
        if B.FOOTER not in page.get_text():
            x, y, fs = place_footer(page)
            page.insert_text((x, y), B.FOOTER, fontsize=fs, fontname="helv", color=(0.2, 0.2, 0.2))
    if fix:
        B.pdf_metadata(doc, doc.metadata.get("title") or Path(path).stem)
        tmp = Path(str(path) + ".tmp")
        doc.save(str(tmp), garbage=3, deflate=True)
        doc.close()
        if backup:
            shutil.copy2(path, Path(path).with_suffix(".pre-branding.pdf"))
        tmp.replace(path)
    return report


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("pdfs", nargs="+")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--no-backup", action="store_true")
    a = ap.parse_args()
    bad = 0
    for p in a.pdfs:
        rep = process(p, fix=not a.check, backup=not a.no_backup)
        if a.check:
            left = rep
        else:
            left = [r for r in process(p, fix=False) if r[1] != "ok"]
        for pg, kind, txt in left:
            print(f"{p}: page {pg}: {kind}: {txt[:120]}")
        bad += len(left)
        if not a.check:
            print(f"{p}: fixed {len([r for r in rep if r[1] != 'warn'])} credit(s); {len(left)} left to word by hand")
    sys.exit(1 if bad and a.check else 0)


if __name__ == "__main__":
    main()
